def quantity(id: str) -> Quantity:
    return CATALOGUE[id]


def ledger_ids() -> frozenset[str]:
    """Every ledger id the catalogue resolves to (the left side of Section 9.11's set difference)."""
    return frozenset(q.ledger_id for q in CATALOGUE.values())


def by_level(level: int) -> tuple[Quantity, ...]:
    return tuple(q for q in CATALOGUE.values() if q.level == level)


