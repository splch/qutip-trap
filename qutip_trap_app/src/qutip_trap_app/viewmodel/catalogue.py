"""The catalogue of displayed quantities and their provenance (PLAN.md Sections 14.1 rule 3, 14.5; Section 9.11 row
"Provenance coverage").

Every number or formula a level shows is a :class:`Quantity` here: a plain-language label (what a newcomer reads first),
the physics term and symbol (what an expert scans for), the unit, the zoom level it first appears at, the Part II section
that governs it and the ledger id its chip resolves to. The static test of Section 9.11 is the set difference between the
ledger ids used here and the ledger: a quantity whose id the ledger lacks fails the build. View-models emit
:class:`Shown` values that name their quantity, so a screen cannot show a number without a chip (Section 14.1: "A quantity
without a tag is a bug").
"""

from __future__ import annotations

from dataclasses import dataclass

Level = int


@dataclass(frozen=True)
class Quantity:
    id: str
    label: str
    """Plain language first (Section 14.5 "Units and conventions"; the ui-ux rule of plain-language labels)."""
    term: str
    """The physics term and symbol the label expands to on hover."""
    unit: str
    level: Level
    section: str
    """The Part II (or Section 13) subsection the explain panel opens."""
    ledger_id: str


@dataclass(frozen=True)
class Shown:
    """A displayed value with the quantity it is an instance of (and therefore its chip)."""

    quantity: str
    value: float | int | str | bool | None
    detail: str = ""

    def __post_init__(self) -> None:
        if self.quantity not in CATALOGUE:
            raise KeyError(
                f"{self.quantity!r} is not in the catalogue: add it with its ledger id before showing it"
            )


def _q(id: str, label: str, term: str, unit: str, level: int, section: str, ledger_id: str) -> Quantity:
    return Quantity(id, label, term, unit, level, section, ledger_id)


